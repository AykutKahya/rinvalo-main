/**
 * Two languages, one site. Turkish lives at the root (/mac/...), English under /en (/en/match/...).
 * Pages and components take a `lang` prop and read every visible word from `dict(lang)`.
 */

export type Lang = "tr" | "en";
export const LANGS: Lang[] = ["tr", "en"];

const ROUTES = {
  tr: {
    home: "/",
    match: "/mac",
    league: "/lig",
    team: "/takim",
    leagues: "/ligler",
    headlines: "/manset",
    analysis: "/analiz",
    power: "/analiz/guc",
    surprises: "/analiz/surprizler",
    accuracy: "/analiz/basari",
  },
  en: {
    home: "/en",
    match: "/en/match",
    league: "/en/league",
    team: "/en/team",
    leagues: "/en/leagues",
    headlines: "/en/headlines",
    analysis: "/en/analysis",
    power: "/en/analysis/power",
    surprises: "/en/analysis/surprises",
    accuracy: "/en/analysis/accuracy",
  },
} as const;

export type RouteKey = keyof (typeof ROUTES)["tr"];

export function paths(lang: Lang) {
  const r = ROUTES[lang];
  return {
    ...r,
    matchOf: (id: string) => `${r.match}/${id}`,
    leagueOf: (code: string) => `${r.league}/${code}`,
    teamOf: (slug: string) => `${r.team}/${slug}`,
  };
}

/** The same page in the other language, e.g. /mac/x-y ⇄ /en/match/x-y. */
export function switchPath(path: string, to: Lang): string {
  const from: Lang = path === "/en" || path.startsWith("/en/") ? "en" : "tr";
  if (from === to) return path;
  const keys = (Object.keys(ROUTES[from]) as RouteKey[]).filter((k) => k !== "home").sort((a, b) => ROUTES[from][b].length - ROUTES[from][a].length);
  for (const k of keys) {
    const base = ROUTES[from][k];
    if (path === base || path.startsWith(`${base}/`)) return ROUTES[to][k] + path.slice(base.length);
  }
  return ROUTES[to].home;
}

/** hreflang alternates for page metadata. */
export function alternates(lang: Lang, key: RouteKey, tail = "") {
  const tr = ROUTES.tr[key] === "/" && tail ? tail : ROUTES.tr[key] + tail;
  const en = ROUTES.en[key] + tail;
  return { canonical: lang === "tr" ? tr : en, languages: { tr, en, "x-default": tr } };
}

